// Generate docs/schema.sql (DDL + sample rows) from the model embedded in src/hub/database.html,
// and check that every step only references columns and rows that exist.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'src/hub/database.html'), 'utf8');
const M = JSON.parse(html.match(/<script type="application\/json" id="model-data">([\s\S]*?)<\/script>/)[1]);
const T = Object.fromEntries(M.tables.map(t => [t.name, t]));
const errs = [];
M.steps.forEach(s => s.ops.forEach(o => {
  const t = T[o.t]; if (!t) return errs.push(`${s.id}: no table ${o.t}`);
  const names = t.cols.map(c => c[0]);
  [...(o.r || []), ...(o.w || [])].forEach(c => { if (!names.includes(c)) errs.push(`${s.id}: ${o.t}.${c} missing`); });
  (o.rows || []).forEach(i => { if (i >= t.rows.length) errs.push(`${s.id}: ${o.t} row ${i} missing`); });
}));
M.tables.forEach(t => t.rows.forEach((r, i) => { if (r.length !== t.cols.length) errs.push(`${t.name} row ${i}: ${r.length} values for ${t.cols.length} columns`); }));
// FK values must exist in the parent table's PK
M.tables.forEach(t => t.cols.forEach((c, j) => {
  const fk = (c[2] || '').split(',').find(f => f.startsWith('FK:')); if (!fk) return;
  const p = T[fk.slice(3)], pk = p.cols.findIndex(x => x[0] === c[0] || (x[2] || '').includes('PK') && (x[0] === c[0] || p.cols.filter(y => (y[2] || '').includes('PK')).length === 1));
  const vals = new Set(p.rows.map(r => r[pk]));
  t.rows.forEach(r => { if (r[j] !== null && !vals.has(r[j])) errs.push(`${t.name}.${c[0]} = ${r[j]} not in ${p.name}`); });
}));
if (errs.length) { console.error(errs.join('\n')); process.exit(1); }

const q = v => v === null ? 'NULL' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
let out = `-- Chronic Care Loop · relational backend (PostgreSQL)\n-- Generated by tools/gen_schema.js from src/hub/database.html. Sample rows come from tools/gen_model.py (a scripted demo day over the extract sample).\n\n`;
const order = ['care_team_user', 'ingest_run', 'src_member_row', 'data_issue', 'rule_need_class', 'rule_trigger', 'rule_condition', 'rule_action', 'rule_tier', 'rule_alert', 'rule_contact_priority', 'rule_gap_state', 'rule_writeback', 'member', 'feature', 'member_feature', 'cohort', 'cohort_rule', 'cohort_member', 'campaign', 'campaign_cohort', 'assessment', 'signal', 'care_plan', 'care_plan_need', 'action', 'contact', 'outcome', 'event_log'];
const ordered = order.concat(M.tables.map(t => t.name).filter(n => !order.includes(n))).map(n => T[n]);
ordered.forEach(t => {
  const pk = t.cols.filter(c => (c[2] || '').includes('PK')).map(c => c[0]);
  const lines = t.cols.map(c => `  ${c[0].padEnd(16)} ${c[1].toUpperCase()}${(c[2] || '').includes('NULL') ? '' : ' NOT NULL'}`);
  lines.push(`  PRIMARY KEY (${pk.join(', ')})`);
  const fks = {};
  t.cols.forEach(c => { const f = (c[2] || '').split(',').find(x => x.startsWith('FK:')); if (f) (fks[f.slice(3)] = fks[f.slice(3)] || []).push(c[0]); });
  Object.entries(fks).forEach(([p, cols]) => {
    const pc = T[p].cols.filter(c => (c[2] || '').includes('PK')).map(c => c[0]);
    if (cols.length === pc.length && pc.length > 1) lines.push(`  FOREIGN KEY (${cols.join(', ')}) REFERENCES ${p} (${pc.join(', ')})`);
    else cols.forEach(c => lines.push(`  FOREIGN KEY (${c}) REFERENCES ${p} (${pc[0]})`));
  });
  out += `-- ${t.purpose}\nCREATE TABLE ${t.name} (\n${lines.join(',\n')}\n);\n\n`;
});
out += `-- One care-plan need has at most one care-plan action\nCREATE UNIQUE INDEX action_one_per_need ON action (need_id) WHERE kind = 'care_plan';\n-- Nightly run picks up unprocessed outcomes\nCREATE INDEX outcome_unprocessed ON outcome (recorded_at) WHERE processed_at IS NULL;\n\n-- Sample data (demo day 20 Nov 2026)\n`;
ordered.forEach(t => {
  out += `INSERT INTO ${t.name} (${t.cols.map(c => c[0]).join(', ')}) VALUES\n${t.rows.map(r => '  (' + r.map(q).join(', ') + ')').join(',\n')};\n\n`;
});
fs.writeFileSync(path.join(root, 'docs/schema.sql'), out);
console.log(`ok · ${M.tables.length} tables · ${M.steps.length} steps · ${M.tables.reduce((s, t) => s + t.rows.length, 0)} sample rows → docs/schema.sql`);
